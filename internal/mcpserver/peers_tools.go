// resolvePeerInterface mirrors internal/cli's helper of the same name: a
// peer's own metadata (set at peer_add time) is a better answer than
// guessing on a multi-interface server, where peerops.ResolveInterface's
// "exactly one active interface, or tell me which" fallback can't know
// which interface a *specific* peer lives on.
func (s *Server) resolvePeerInterface(ctx context.Context, client *sshtransport.Client, metaInterface, argInterface string) (string, error) {
	if metaInterface != "" {
		return metaInterface, nil
	}
	return peerops.ResolveInterface(ctx, client, argInterface)
}

type PeerListArgs struct {
	ServerID string `json:"server_id" jsonschema:"the wgtui server ID from list_servers"`
	Credentials
}

// PeerListResult wraps the peer slice in a named field - see
// ServerListResult's doc comment for why a bare slice return breaks tool
// discovery for MCP clients that require an object-shaped outputSchema.
type PeerListResult struct {
	Peers []peerview.Peer `json:"peers"`
}

func (s *Server) peerList(ctx context.Context, req *mcp.CallToolRequest, args PeerListArgs) (*mcp.CallToolResult, PeerListResult, error) {
	client, target, cleanup, err := s.connect(ctx, args.ServerID, args.Credentials)
	if err != nil {
		return nil, PeerListResult{}, err
	}
	defer cleanup()
	prompts := args.Credentials.prompts()

	if err := client.SudoValidate(ctx, prompts); err != nil {
		return nil, PeerListResult{}, fmt.Errorf("sudo: %w", err)
	}
	res, err := client.RunSudo(ctx, "wg show all dump", prompts)
	if err != nil {
		return nil, PeerListResult{}, fmt.Errorf("wg show all dump: %w", err)
	}
	if res.ExitCode != 0 {
		return nil, PeerListResult{}, fmt.Errorf("wg show all dump exited %d: %s", res.ExitCode, res.Stderr)
	}
	dump, err := wgconfig.ParseDump(string(res.Stdout))
	if err != nil {
		return nil, PeerListResult{}, fmt.Errorf("parse wg dump: %w", err)
	}

	views := peerview.Reconcile(dump.Peers, s.vault.ListPeers(target.ID), func(pubKey string) bool {
		_, ok := s.vault.GetProfile(target.ID, pubKey)
		return ok
	}, time.Now())

	return textResult(fmt.Sprintf("%d peer(s)", len(views))), PeerListResult{Peers: views}, nil
}

type PeerAddArgs struct {
	ServerID     string   `json:"server_id" jsonschema:"the wgtui server ID from list_servers"`
	Name         string   `json:"name" jsonschema:"display name for the new peer (required, must be unique for this server)"`
	SplitTunnel  []string `json:"split_tunnel,omitempty" jsonschema:"CIDRs the client should route through the tunnel; omit for a full tunnel (0.0.0.0/0, ::/0)"`
	Keepalive    int      `json:"keepalive,omitempty" jsonschema:"PersistentKeepalive seconds for the client profile; omitted or <=0 defaults to 25"`
	DNS          []string `json:"dns,omitempty" jsonschema:"DNS servers for the client profile; omitted defaults to Google DNS 8.8.8.8 and 8.8.4.4"`
	EndpointHost string   `json:"endpoint_host,omitempty" jsonschema:"VPN endpoint hostname/IP for the client profile, if different from the server's SSH host"`
	Interface    string   `json:"interface,omitempty" jsonschema:"WireGuard interface (auto-detected if the server has only one active)"`
	NoPSK        bool     `json:"no_psk,omitempty" jsonschema:"skip generating a preshared key (a preshared key is generated by default)"`
	Confirm      bool     `json:"confirm,omitempty" jsonschema:"false (default) only computes and returns the plan; true actually creates the peer on the server. Never set true without a user-approved confirm=false preview first."`
	Credentials
}

type PeerAddResult struct {
	Applied    bool   `json:"applied"`
	Plan       string `json:"plan"`
	Name       string `json:"name,omitempty"`
	PublicKey  string `json:"public_key,omitempty"`
	VPNAddress string `json:"vpn_address,omitempty"`
	BackupPath string `json:"backup_path,omitempty"`
}

// peerAdd never returns the client's private key or the rendered client
// profile through the tool result - only the vault-local, non-secret
// summary (name/public key/VPN address). The profile is always saved to
// the local vault; retrieving the actual .conf (a secret) is left to the
// existing `wgtui peer export` CLI command, which is a deliberate v1
// scope boundary (see docs/THREAT_MODEL.md's MCP section): this keeps
// every mcpserver tool response entirely secret-free, rather than having
// to reason about a private key landing in an agent's conversation
// context by default.
func (s *Server) peerAdd(ctx context.Context, req *mcp.CallToolRequest, args PeerAddArgs) (*mcp.CallToolResult, PeerAddResult, error) {
	if args.Name == "" {
		return nil, PeerAddResult{}, fmt.Errorf("name is required")
	}
	if _, exists := s.vault.GetPeerByName(args.ServerID, args.Name); exists {
		return nil, PeerAddResult{}, fmt.Errorf("a peer named %q is already registered for %q", args.Name, args.ServerID)
	}
	if len(args.DNS) == 0 {
		args.DNS = peerops.DefaultDNS()
	}

	client, target, cleanup, err := s.connect(ctx, args.ServerID, args.Credentials)
	if err != nil {
		return nil, PeerAddResult{}, err
	}
	defer cleanup()
	prompts := args.Credentials.prompts()

	resolvedIface, err := peerops.ResolveInterface(ctx, client, args.Interface)
	if err != nil {
		return nil, PeerAddResult{}, err
	}
	cc, err := peerops.FetchCurrentConfig(ctx, client, prompts, resolvedIface)
	if err != nil {
		return nil, PeerAddResult{}, err
	}

	addr, err := peerops.NextFreeAddress(cc.VPNCIDR, cc.UsedAddresses)
	if err != nil {
		return nil, PeerAddResult{}, fmt.Errorf("allocate VPN address: %w", err)
	}
	// The server-side peer block's AllowedIPs governs which source
	// addresses this peer may claim - always just its own assigned
	// address, never 0.0.0.0/0, regardless of tunnel mode. Full/split
	// tunnel only affects the *client's* AllowedIPs below.
	serverAllowedIPs := []string{addr.String() + "/32"}

	fullTunnel := len(args.SplitTunnel) == 0
	clientAllowedIPs := args.SplitTunnel
	if fullTunnel {
		clientAllowedIPs = []string{"0.0.0.0/0", "::/0"}
	}

	keepalive := args.Keepalive
	if keepalive <= 0 {
		keepalive = 25
	}

	plan := fmt.Sprintf("+ peer %s\n+ server allowed_ips: %s\n+ client vpn address: %s\n+ client mode: %s\n+ interface: %s",
		args.Name, serverAllowedIPs[0], addr, tunnelLabel(fullTunnel), resolvedIface)
	if !args.Confirm {
		return textResult("Plan only (confirm=false) - nothing changed:\n" + plan), PeerAddResult{Plan: plan}, nil
	}

	result, err := peerops.AddPeer(ctx, client, prompts, cc, args.Name, serverAllowedIPs, keepalive, !args.NoPSK)
	if err != nil {
		return nil, PeerAddResult{}, err
	}

	host := args.EndpointHost
	if host == "" {
		host = target.SSHHostOrAlias
	}
	clientConf := peerops.BuildClientProfile(peerops.ClientProfileParams{
		ClientPrivateKey:    result.KeyPair.PrivateKey,
		ClientAddress:       addr,
		DNS:                 args.DNS,
		ServerPublicKey:     cc.ServerPublicKey,
		PresharedKey:        result.PresharedKey,
		EndpointHost:        host,
		EndpointPort:        cc.ListenPort,
		AllowedIPs:          clientAllowedIPs,
		PersistentKeepalive: keepalive,
	})

	s.vault.SetProfile(args.ServerID, result.KeyPair.PublicKey, clientConf)
	_ = s.vault.AddPeer(profilevault.PeerMetadata{
		ServerID: args.ServerID, Name: args.Name, PublicKey: result.KeyPair.PublicKey,
		Interface: resolvedIface, CreatedAt: time.Now(), Status: profilevault.PeerStatusActive,
	})
	if err := s.vault.Save(s.vaultPath); err != nil {
		return nil, PeerAddResult{}, fmt.Errorf("peer was created on the server but saving the local vault failed: %w - "+
			"the client profile could not be saved locally; use `wgtui peer revoke` via the CLI to remove it from the server, or retry saving",
			err)
	}

	return textResult(fmt.Sprintf("Added peer %q, VPN address %s. Use `wgtui peer export` to retrieve the client profile file.", args.Name, addr)),
		PeerAddResult{Applied: true, Plan: plan, Name: args.Name, PublicKey: result.KeyPair.PublicKey, VPNAddress: addr.String(), BackupPath: result.Outcome.BackupPath}, nil
}

func tunnelLabel(full bool) string {
	if full {
		return "full tunnel"
	}
	return "split tunnel"
}

type PeerTargetArgs struct {
	ServerID  string `json:"server_id" jsonschema:"the wgtui server ID from list_servers"`
	Name      string `json:"name" jsonschema:"the peer's display name, as shown by peer_list"`
	Interface string `json:"interface,omitempty" jsonschema:"interface the peer is on; only needed if the peer's metadata doesn't already record it"`
	Confirm   bool   `json:"confirm,omitempty" jsonschema:"false (default) only computes and returns the plan; true actually applies it. Never set true without a user-approved confirm=false preview first."`
	Credentials
}

type PeerActionResult struct {
	Applied    bool   `json:"applied"`
	Plan       string `json:"plan"`
	BackupPath string `json:"backup_path,omitempty"`
}

func (s *Server) peerDisable(ctx context.Context, req *mcp.CallToolRequest, args PeerTargetArgs) (*mcp.CallToolResult, PeerActionResult, error) {
	meta, ok := s.vault.GetPeerByName(args.ServerID, args.Name)
	if !ok {
		return nil, PeerActionResult{}, fmt.Errorf("no peer named %q registered for %q", args.Name, args.ServerID)
	}
	if meta.Status == profilevault.PeerStatusDisabled {
		return nil, PeerActionResult{}, fmt.Errorf("%q is already disabled", args.Name)
	}

	client, _, cleanup, err := s.connect(ctx, args.ServerID, args.Credentials)
	if err != nil {
		return nil, PeerActionResult{}, err
	}
	defer cleanup()
	prompts := args.Credentials.prompts()

	resolvedIface, err := s.resolvePeerInterface(ctx, client, meta.Interface, args.Interface)
	if err != nil {
		return nil, PeerActionResult{}, err
	}
	cc, err := peerops.FetchCurrentConfig(ctx, client, prompts, resolvedIface)
	if err != nil {
		return nil, PeerActionResult{}, err
	}

	plan := fmt.Sprintf("- peer %s (%s): removed from runtime and persistent config; local profile and metadata kept for resume", args.Name, peerview.ShortenKey(meta.PublicKey))
	if !args.Confirm {
		return textResult("Plan only (confirm=false) - nothing changed:\n" + plan), PeerActionResult{Plan: plan}, nil
	}

	outcome, rawBlock, err := peerops.DisablePeer(ctx, client, prompts, cc, meta.PublicKey)
	if err != nil {
		return nil, PeerActionResult{}, err
	}

	meta.Status = profilevault.PeerStatusDisabled
	meta.DisabledBlockRaw = rawBlock
	meta.Interface = resolvedIface
	s.vault.UpdatePeer(meta)
	if err := s.vault.Save(s.vaultPath); err != nil {
		return nil, PeerActionResult{}, fmt.Errorf("access was paused on the server but local metadata could not be saved: %w", err)
	}

	return textResult(fmt.Sprintf("Paused %q. Server access removed; local profile kept.", args.Name)),
		PeerActionResult{Applied: true, Plan: plan, BackupPath: outcome.BackupPath}, nil
}

func (s *Server) peerEnable(ctx context.Context, req *mcp.CallToolRequest, args PeerTargetArgs) (*mcp.CallToolResult, PeerActionResult, error) {
	meta, ok := s.vault.GetPeerByName(args.ServerID, args.Name)
	if !ok {
		return nil, PeerActionResult{}, fmt.Errorf("no peer named %q registered for %q", args.Name, args.ServerID)
	}
	if meta.Status != profilevault.PeerStatusDisabled || meta.DisabledBlockRaw == "" {
		return nil, PeerActionResult{}, fmt.Errorf("%q is not currently disabled", args.Name)
	}

	client, _, cleanup, err := s.connect(ctx, args.ServerID, args.Credentials)
	if err != nil {
		return nil, PeerActionResult{}, err
	}
	defer cleanup()
	prompts := args.Credentials.prompts()

	resolvedIface, err := s.resolvePeerInterface(ctx, client, meta.Interface, args.Interface)
	if err != nil {
		return nil, PeerActionResult{}, err
	}
	cc, err := peerops.FetchCurrentConfig(ctx, client, prompts, resolvedIface)
	if err != nil {
		return nil, PeerActionResult{}, err
	}

	plan := fmt.Sprintf("+ peer %s (%s): restored to persistent config exactly as it was before disabling", args.Name, peerview.ShortenKey(meta.PublicKey))
	if !args.Confirm {
		return textResult("Plan only (confirm=false) - nothing changed:\n" + plan), PeerActionResult{Plan: plan}, nil
	}

	outcome, err := peerops.EnablePeer(ctx, client, prompts, cc, meta.DisabledBlockRaw)
	if err != nil {
		return nil, PeerActionResult{}, err
	}

	meta.Status = profilevault.PeerStatusActive
	meta.DisabledBlockRaw = ""
	meta.Interface = resolvedIface
	s.vault.UpdatePeer(meta)
	if err := s.vault.Save(s.vaultPath); err != nil {
		return nil, PeerActionResult{}, fmt.Errorf("access was resumed on the server but local metadata could not be saved: %w", err)
	}

	return textResult(fmt.Sprintf("Resumed %q. Server access restored.", args.Name)),
		PeerActionResult{Applied: true, Plan: plan, BackupPath: outcome.BackupPath}, nil
}

type PeerRevokeArgs struct {
	ServerID       string `json:"server_id" jsonschema:"the wgtui server ID from list_servers"`
	Name           string `json:"name" jsonschema:"the peer's display name, as shown by peer_list"`
	Interface      string `json:"interface,omitempty" jsonschema:"interface the peer is on; only needed if the peer's metadata doesn't already record it"`
	DeleteProfile  bool   `json:"delete_profile,omitempty" jsonschema:"also delete the local client profile, which contains the private key. Never set true unless the user explicitly asked to delete the saved profile too."`
	DeleteMetadata bool   `json:"delete_metadata,omitempty" jsonschema:"also delete the local peer metadata entry"`
	Confirm        bool   `json:"confirm,omitempty" jsonschema:"false (default) only computes and returns the plan; true actually applies it. Never set true without a user-approved confirm=false preview first."`
	Credentials
}

func (s *Server) peerRevoke(ctx context.Context, req *mcp.CallToolRequest, args PeerRevokeArgs) (*mcp.CallToolResult, PeerActionResult, error) {
	meta, ok := s.vault.GetPeerByName(args.ServerID, args.Name)
	if !ok {
		return nil, PeerActionResult{}, fmt.Errorf("no peer named %q registered for %q", args.Name, args.ServerID)
	}

	plan := fmt.Sprintf("Revoke server access for %s (%s). delete_profile=%v delete_metadata=%v",
		args.Name, peerview.ShortenKey(meta.PublicKey), args.DeleteProfile, args.DeleteMetadata)
	if !args.Confirm {
		return textResult("Plan only (confirm=false) - nothing changed:\n" + plan), PeerActionResult{Plan: plan}, nil
	}

	client, _, cleanup, err := s.connect(ctx, args.ServerID, args.Credentials)
	if err != nil {
		return nil, PeerActionResult{}, err
	}
	defer cleanup()
	prompts := args.Credentials.prompts()

	var outcome transaction.Outcome
	if meta.Status != profilevault.PeerStatusDisabled {
		resolvedIface, err := s.resolvePeerInterface(ctx, client, meta.Interface, args.Interface)
		if err != nil {
			return nil, PeerActionResult{}, err
		}
		cc, err := peerops.FetchCurrentConfig(ctx, client, prompts, resolvedIface)
		if err != nil {
			return nil, PeerActionResult{}, err
		}
		outcome, err = peerops.RevokePeer(ctx, client, prompts, cc, meta.PublicKey)
		if err != nil {
			return nil, PeerActionResult{}, err
		}
	}

	if args.DeleteProfile {
		s.vault.DeleteProfile(args.ServerID, meta.PublicKey)
	}
	if args.DeleteMetadata {
		s.vault.RemovePeer(args.ServerID, meta.PublicKey)
	} else {
		meta.Status = profilevault.PeerStatusRevoked
		meta.DisabledBlockRaw = ""
		s.vault.UpdatePeer(meta)
	}
	if err := s.vault.Save(s.vaultPath); err != nil {
		return nil, PeerActionResult{}, fmt.Errorf("server change applied but failed to save the local vault: %w", err)
	}

	return textResult(fmt.Sprintf("Revoked %q. profile_deleted=%v metadata_deleted=%v.", args.Name, args.DeleteProfile, args.DeleteMetadata)),
		PeerActionResult{Applied: true, Plan: plan, BackupPath: outcome.BackupPath}, nil
}

type PeerRotateResult struct {
	Applied      bool   `json:"applied"`
	Plan         string `json:"plan"`
	OldPublicKey string `json:"old_public_key,omitempty"`
	NewPublicKey string `json:"new_public_key,omitempty"`
	BackupPath   string `json:"backup_path,omitempty"`
}

func (s *Server) peerRotate(ctx context.Context, req *mcp.CallToolRequest, args PeerTargetArgs) (*mcp.CallToolResult, PeerRotateResult, error) {
	meta, ok := s.vault.GetPeerByName(args.ServerID, args.Name)
	if !ok {
		return nil, PeerRotateResult{}, fmt.Errorf("no peer named %q registered for %q", args.Name, args.ServerID)
	}
	if meta.Status != profilevault.PeerStatusActive {
		return nil, PeerRotateResult{}, fmt.Errorf("%q is not active (status=%s)", args.Name, meta.Status)
	}
	oldProfile, hadProfile := s.vault.GetProfile(args.ServerID, meta.PublicKey)

	client, target, cleanup, err := s.connect(ctx, args.ServerID, args.Credentials)
	if err != nil {
		return nil, PeerRotateResult{}, err
	}
	defer cleanup()
	prompts := args.Credentials.prompts()

	resolvedIface, err := s.resolvePeerInterface(ctx, client, meta.Interface, args.Interface)
	if err != nil {
		return nil, PeerRotateResult{}, err
	}
	cc, err := peerops.FetchCurrentConfig(ctx, client, prompts, resolvedIface)
	if err != nil {
		return nil, PeerRotateResult{}, err
	}

	oldBlockIdx := cc.Doc.FindPeerByPublicKey(meta.PublicKey)
	if oldBlockIdx == -1 {
		return nil, PeerRotateResult{}, fmt.Errorf("peer %s not found in the current config (is it disabled?)", peerview.ShortenKey(meta.PublicKey))
	}
	oldBlock := cc.Doc.Blocks[oldBlockIdx]
	allowedIPs := peerops.SplitTrim(oldBlock.Value("AllowedIPs"), ",")
	keepalive, _ := strconv.Atoi(oldBlock.Value("PersistentKeepalive"))
	withPSK := oldBlock.Value("PresharedKey") != ""

	plan := fmt.Sprintf("Rotate %s: new keypair replaces %s on the server; old local profile removed", args.Name, peerview.ShortenKey(meta.PublicKey))
	if !args.Confirm {
		return textResult("Plan only (confirm=false) - nothing changed:\n" + plan), PeerRotateResult{Plan: plan, OldPublicKey: meta.PublicKey}, nil
	}

	result, err := peerops.RotatePeer(ctx, client, prompts, cc, meta.PublicKey, args.Name, allowedIPs, keepalive, withPSK)
	if err != nil {
		return nil, PeerRotateResult{}, err
	}

	clientAddr, endpointHost, endpointPort, clientAllowedIPs, dnsList := peerops.RotateProfileParams(oldProfile, hadProfile, allowedIPs, target.SSHHostOrAlias, cc.ListenPort)

	newConf := peerops.BuildClientProfile(peerops.ClientProfileParams{
		ClientPrivateKey:    result.KeyPair.PrivateKey,
		ClientAddress:       clientAddr,
		DNS:                 dnsList,
		ServerPublicKey:     cc.ServerPublicKey,
		PresharedKey:        result.PresharedKey,
		EndpointHost:        endpointHost,
		EndpointPort:        endpointPort,
		AllowedIPs:          clientAllowedIPs,
		PersistentKeepalive: keepalive,
	})

	oldPublicKey := meta.PublicKey
	s.vault.DeleteProfile(args.ServerID, oldPublicKey)
	s.vault.SetProfile(args.ServerID, result.KeyPair.PublicKey, newConf)
	s.vault.RemovePeer(args.ServerID, oldPublicKey)
	meta.PublicKey = result.KeyPair.PublicKey
	meta.Interface = resolvedIface
	_ = s.vault.AddPeer(meta)

	if err := s.vault.Save(s.vaultPath); err != nil {
		return nil, PeerRotateResult{}, fmt.Errorf("keys were rotated on the server but saving the local vault failed: %w", err)
	}

	return textResult(fmt.Sprintf("Rotated %q: %s -> %s. New local profile saved.", args.Name, peerview.ShortenKey(oldPublicKey), peerview.ShortenKey(result.KeyPair.PublicKey))),
		PeerRotateResult{Applied: true, Plan: plan, OldPublicKey: oldPublicKey, NewPublicKey: result.KeyPair.PublicKey, BackupPath: result.Outcome.BackupPath}, nil
}
